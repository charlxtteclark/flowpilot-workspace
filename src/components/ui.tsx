/* ---------- multi-select filter popover ---------- */
export function MultiSelect({ id, label, options, value, onChange }: { id: string; label: string; options: { value: string; label: string; count?: number }[]; value: string[]; onChange: (v: string[]) => void }) {
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const h = (e: MouseEvent) => { if (ref.current && !ref.current.contains(e.target as Node)) setOpen(false); };
    document.addEventListener("mousedown", h);
    return () => document.removeEventListener("mousedown", h);
  }, []);
  const active = value.length > 0;
  return (
    <div className="relative" ref={ref}>
      <button id={id} type="button" className={`btn !py-1 !text-xs ${active ? "!border-accent !text-accent" : ""}`} aria-expanded={open} onClick={() => setOpen((o) => !o)}>
        {label}{active && <span className="rounded bg-accentsoft px-1 tnum">{value.length}</span>}<Icon name="down" size={12} />
      </button>
      {open && (
        <div className="absolute left-0 z-30 mt-1 max-h-72 w-60 overflow-auto rounded-lg border border-line bg-surface p-1 shadow-lg" role="listbox" aria-label={label}>
          {options.map((o) => {
            const on = value.includes(o.value);
            return (
              <label key={o.value} className="flex cursor-pointer items-center gap-2 rounded px-2 py-1.5 text-[13px] hover:bg-surface2">
                <input type="checkbox" checked={on} onChange={() => onChange(on ? value.filter((v) => v !== o.value) : [...value, o.value])} />
                <span className="flex-1 truncate">{o.label}</span>
                {o.count != null && <span className="text-2xs text-ink3 tnum">{o.count}</span>}
              </label>
            );
          })}
          {active && <button className="mt-1 w-full rounded px-2 py-1 text-left text-xs text-accent hover:bg-surface2" onClick={() => onChange([])}>Clear</button>}
        </div>
      )}
    </div>
  );
}

export function fmtDate(iso?: string) {
  if (!iso) return "—";
  const d = new Date(iso);
  if (isNaN(d.getTime())) return iso;
  return d.toLocaleString(undefined, { month: "short", day: "numeric", year: "numeric", hour: "numeric", minute: "2-digit" });
}
export const fmtRating = (n: number | null | undefined, max?: number) => (n == null ? "—" : `${(Math.round(n * 10) / 10).toFixed(1)}/${max ?? 5}`);

export function Toast({ msg, onDone }: { msg: string | null; onDone: () => void }) {
  useEffect(() => { if (!msg) return; const t = setTimeout(onDone, 3200); return () => clearTimeout(t); }, [msg, onDone]);
  if (!msg) return null;
  return <div role="status" className="fixed bottom-4 left-1/2 z-50 -translate-x-1/2 rounded-lg bg-ink px-4 py-2 text-[13px] text-bg shadow-lg">{msg}</div>;
}
