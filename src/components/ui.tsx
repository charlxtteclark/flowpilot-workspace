/* ---------- priority + grades ---------- */
export const PRIORITY_STYLE: Record<Priority, string> = {
  High: "bg-critsoft text-crit",
  Medium: "bg-warnsoft text-warn",
  Lower: "bg-lowsoft text-low",
};
export function PriorityPill({ p, strike = false, size = "md" }: { p: Priority; strike?: boolean; size?: "sm" | "md" }) {
  const glyph = p === "High" ? "▲" : p === "Medium" ? "■" : "▼";
  return (
    <span className={`inline-flex items-center gap-1 rounded-full font-semibold whitespace-nowrap ${size === "sm" ? "text-2xs px-1.5 py-0.5" : "text-xs px-2 py-0.5"} ${PRIORITY_STYLE[p]} ${strike ? "line-through opacity-60" : ""}`}>
      <span aria-hidden="true" className="text-[8px]">{glyph}</span>{p}
    </span>
  );
}

/** Signal strength meter — neutral ink, so it never competes with priority colors. */
export function Meter({ g, label }: { g: Grade; label?: string }) {
  const n = g === "High" ? 3 : g === "Medium" ? 2 : g === "Low" ? 1 : 0;
  return (
    <span className="inline-flex items-center gap-1.5 whitespace-nowrap" title={label ? `${label}: ${g}` : g}>
      <span className="inline-flex items-end gap-[2px]" aria-hidden="true">
        {[0, 1, 2].map((i) => (
          <span key={i} className={`w-[4px] rounded-[1px] ${i < n ? "bg-ink" : "bg-line"}`} style={{ height: 6 + i * 3 }} />
        ))}
      </span>
      <span className={`text-xs ${g === "N/A" ? "text-ink3" : "text-ink2"}`}>{g === "N/A" ? "No data" : g}</span>
    </span>
  );
}

